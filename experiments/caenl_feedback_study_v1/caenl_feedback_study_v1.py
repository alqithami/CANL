def launch(resume=False,check_only=False):
    if tmux_active() or lock_active():
        print('Campaign worker already active. No duplicate process started.');status();return 0
    if (ROOT/'COMPLETE.json').exists():status();return 0
    if (ROOT/'FAILED.json').exists() and not resume:
        status();raise RuntimeError('After resolving the reported error, use --resume to continue from existing checkpoints.')
    if not check_only:require(shutil.which('tmux'),'tmux is unavailable. No run was started. Share this error.')
    python=prepare();command=engine_command(python,check_only)
    settings={'PYTHONUNBUFFERED':'1','PYTHONDONTWRITEBYTECODE':'1','CUBLAS_WORKSPACE_CONFIG':':4096:8'}
    if check_only:
        env=os.environ.copy();env.update(settings)
        return subprocess.run(command,env=env).returncode
    # Only the campaign log is appended; previous errors and run artifacts remain available.
    shell_command='exec env '+' '.join(shlex.quote(k+'='+v) for k,v in settings.items())+' '+shlex.join(command)
    shell_command+=' >> '+shlex.quote(str(ROOT/'run.log'))+' 2>&1'
    subprocess.run(['tmux','new-session','-d','-s',SESSION,'bash','-lc',shell_command],check=True)
    print('STARTED: detached worker; first performs source, CPU, dataset, disk, and CUDA checks.')
    print('You may disconnect from SSH. Check status after about 5 minutes:')
    print('python3 "$HOME/caenl_feedback_study_v1.py" --status')
    print('tail -n 35 '+shlex.quote(str(ROOT/'run.log')))
    print('104 method runs + 23 shared initializations; allow several days. Initial free space: about 160 GiB.')
    print('Results:',ROOT)
    return 0


