def lock_active():
    path=ROOT/'RUN.lock'
    if not path.exists():return False
    with path.open('r') as f:
        try:fcntl.flock(f,fcntl.LOCK_EX|fcntl.LOCK_NB)
        except BlockingIOError:return True
        finally:
            try:fcntl.flock(f,fcntl.LOCK_UN)
            except OSError:pass
    return False


